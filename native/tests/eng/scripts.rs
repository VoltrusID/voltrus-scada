//! Scripts against the live plant: create a script, read it back, update
//! every field, test it with an input (a run that succeeds and one that
//! throws), list its runs, and delete it, leaving the script list as it
//! was.

use std::time::{SystemTime, UNIX_EPOCH};

use serde_json::json;
use voltrus_scada_native::api::VoltrusApi;
use voltrus_scada_native::api::eng_scripts::{CreateScript, HISTORY_LIMIT, MIB, UpdateScript};

const FIRST: &str = "function main(input) {\n  return { value: input.value + 1 };\n}\n";
const SECOND: &str = "// doubled\nfunction main(input) {\n  if (typeof input.value !== 'number') {\n    throw new Error('value must be a number');\n  }\n  return { value: input.value * 2 };\n}\n";

pub(crate) async fn round_trip(api: &VoltrusApi) {
    let before = api.scripts().await.expect("list scripts");
    println!("scripts: {} on the plant", before.len());

    let stamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_millis());
    let name = format!("native e2e {stamp}");
    let created = api
        .create_script(&CreateScript {
            name: name.clone(),
            source: FIRST.into(),
            cpu_limit_ms: 5000,
            memory_limit_bytes: 32 * MIB,
        })
        .await
        .expect("create a script");
    let id = created.id;
    assert_eq!(created.name, name);
    assert_eq!(created.source, FIRST);
    assert_eq!(
        created.syntax_error, None,
        "a valid script has no syntax error"
    );
    assert!(created.enabled, "the server creates scripts enabled");
    assert_eq!(
        (created.cpu_limit_ms, created.memory_limit_bytes),
        (5000, 32 * MIB)
    );
    println!("scripts: created #{id}");

    let listed = api.scripts().await.expect("list scripts again");
    let read = listed
        .iter()
        .find(|script| script.id == id)
        .expect("the new script is listed");
    assert_eq!(read, &created, "the list holds the script as created");
    assert_eq!(listed.len(), before.len() + 1);
    println!("scripts: read #{id} back from the list");

    let renamed = format!("{name} (doubled)");
    let updated = api
        .update_script(
            id,
            &UpdateScript {
                name: Some(renamed.clone()),
                source: Some(SECOND.into()),
                cpu_limit_ms: Some(2000),
                memory_limit_bytes: Some(16 * MIB),
                enabled: Some(false),
            },
        )
        .await
        .expect("update the script");
    assert_eq!(updated.id, id);
    assert_eq!(updated.name, renamed);
    assert_eq!(updated.source, SECOND);
    assert_eq!(
        (updated.cpu_limit_ms, updated.memory_limit_bytes),
        (2000, 16 * MIB)
    );
    assert!(!updated.enabled);
    assert_eq!(updated.syntax_error, None);
    // Only what is sent changes.
    let enabled = api
        .update_script(
            id,
            &UpdateScript {
                enabled: Some(true),
                ..UpdateScript::default()
            },
        )
        .await
        .expect("enable the script");
    assert!(enabled.enabled);
    assert_eq!(enabled.name, renamed, "the name stays");
    assert_eq!(enabled.source, SECOND, "the source stays");
    println!("scripts: updated #{id} (name, source, limits, enabled)");

    let ran = api
        .test_script(id, json!({ "value": 21 }))
        .await
        .expect("test the script");
    assert!(ran.success, "the test ran: {:?}", ran.error);
    let output: serde_json::Value =
        serde_json::from_str(ran.output.as_deref().expect("an output")).expect("JSON output");
    assert_eq!(output, json!({ "value": 42 }));
    assert!(ran.duration_ms.is_some());
    println!("scripts: tested #{id}: {{value: 21}} gave {output}");

    let threw = api
        .test_script(id, json!({ "value": "x" }))
        .await
        .expect("test the script with a bad input");
    assert!(!threw.success);
    let error = threw.error.unwrap_or_default();
    // The server reports a thrown error as QuickJS's generic "Exception
    // generated by QuickJS", not the script's message (a server gap).
    assert!(!error.is_empty(), "the failed run carries an error");
    println!("scripts: tested #{id} with a bad input: {error}");

    let runs = api
        .script_executions(id, HISTORY_LIMIT)
        .await
        .expect("list the script's runs");
    assert_eq!(runs.len(), 2, "one run per test");
    assert!(runs.iter().all(|run| run.script_id == id));
    assert!(runs.iter().all(|run| run.trigger() == "test"));
    let good = runs
        .iter()
        .find(|run| run.succeeded())
        .expect("the run that succeeded");
    assert_eq!(
        serde_json::from_str::<serde_json::Value>(good.output.as_deref().unwrap_or("null"))
            .expect("JSON output"),
        json!({ "value": 42 })
    );
    let bad = runs
        .iter()
        .find(|run| !run.succeeded())
        .expect("the run that failed");
    assert_eq!(bad.status, "error");
    assert!(
        bad.error_message
            .as_deref()
            .is_some_and(|error| !error.is_empty()),
        "the failed run keeps its error"
    );
    let one = api.script_executions(id, 1).await.expect("list one run");
    assert_eq!(one.len(), 1, "the limit holds");
    println!("scripts: #{id} has {} runs", runs.len());

    api.delete_script(id).await.expect("delete the script");
    let after = api.scripts().await.expect("list scripts after");
    assert!(
        after.iter().all(|script| script.id != id),
        "the script is gone"
    );
    assert_eq!(
        after.iter().map(|script| script.id).collect::<Vec<_>>(),
        before.iter().map(|script| script.id).collect::<Vec<_>>(),
        "the plant's scripts are as they were"
    );
    let orphaned = api
        .script_executions(id, HISTORY_LIMIT)
        .await
        .expect("list a deleted script's runs");
    println!(
        "scripts: deleted #{id} ({} runs left behind)",
        orphaned.len()
    );
}
